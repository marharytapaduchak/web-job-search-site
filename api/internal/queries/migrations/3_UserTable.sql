create table users (
    id                   serial        primary key,
    first_name           varchar(255)  default '',
    last_name            varchar(255)  default '',
    email                varchar(255)  default '',
    phone                varchar(50)   default '',
    telegram             varchar(100)  default '',
    linkedin             varchar(500)  default '',
    position             varchar(255)  default '',
    qualification_level  varchar(100)  default '',
    english_level        varchar(100)  default '',
    city                 varchar(255)  default '',
    salary               varchar(100)  default '',
    hourly_rate          varchar(100)  default '',
    portfolio_url        varchar(2048) default '',
    work_format          varchar(100)  default '',
    employment_type      varchar(100)  default '',
    location_scope       varchar(100)  default '',
    about                text          default '',
    positions            jsonb         default '[]',
    languages            jsonb         default '[]',
    work_formats         text[]        default '{}',
    employment_types     text[]        default '{}',
    can_relocate         boolean       default false,
    resume_title         varchar(255)  default '',
    resume_url           varchar(2048) default '',
    resume_added_at      varchar(50)   default '',
    certificates         jsonb         default '[]',
    avatar_style         varchar(100)  default '',
    avatar_seed          varchar(100)  default ''
)
